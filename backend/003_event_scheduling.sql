BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coordinator_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
  time_zone TEXT NOT NULL CHECK (length(btrim(time_zone)) > 0),
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  candidate_buffer_minutes INTEGER NOT NULL DEFAULT 0
    CHECK (candidate_buffer_minutes >= 0),
  interviewer_buffer_minutes INTEGER NOT NULL DEFAULT 0
    CHECK (interviewer_buffer_minutes >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT events_date_range_valid CHECK (end_date >= start_date)
);

CREATE INDEX events_coordinator_active_idx
  ON events (coordinator_id, id) WHERE is_active;

CREATE FUNCTION validate_event_time_zone() RETURNS trigger
LANGUAGE plpgsql
AS $timezone_check$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_timezone_names WHERE name = NEW.time_zone
  ) THEN
    RAISE EXCEPTION 'time_zone must be a valid IANA timezone name.'
      USING ERRCODE = '22023';
  END IF;
  RETURN NEW;
END;
$timezone_check$;

CREATE TRIGGER events_validate_time_zone
  BEFORE INSERT OR UPDATE ON events
  FOR EACH ROW EXECUTE FUNCTION validate_event_time_zone();

CREATE TABLE event_working_hours (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  day_of_week TEXT NOT NULL CHECK (
    day_of_week IN (
      'MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY',
      'FRIDAY', 'SATURDAY', 'SUNDAY'
    )
  ),
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  CONSTRAINT event_working_hours_valid_time CHECK (end_time > start_time),
  CONSTRAINT event_working_hours_unique_start
    UNIQUE (event_id, day_of_week, start_time)
);

CREATE INDEX event_working_hours_event_idx ON event_working_hours (event_id);

CREATE TABLE event_rounds (
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  round_id TEXT NOT NULL CHECK (length(btrim(round_id)) > 0),
  round_order INTEGER NOT NULL CHECK (round_order > 0),
  duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
  required_skills TEXT[] NOT NULL DEFAULT '{}',
  CONSTRAINT event_rounds_pkey PRIMARY KEY (event_id, round_id),
  CONSTRAINT event_rounds_unique_order UNIQUE (event_id, round_order)
);

CREATE TABLE event_candidates (
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  candidate_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT event_candidates_pkey PRIMARY KEY (event_id, candidate_id)
);

CREATE INDEX event_candidates_candidate_idx
  ON event_candidates (candidate_id, event_id);

CREATE TABLE event_candidate_availability (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL,
  candidate_id INTEGER NOT NULL,
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT event_candidate_availability_enrollment_fkey
    FOREIGN KEY (event_id, candidate_id)
    REFERENCES event_candidates(event_id, candidate_id) ON DELETE CASCADE,
  CONSTRAINT event_candidate_availability_valid_time
    CHECK (end_time > start_time),
  CONSTRAINT event_candidate_availability_no_overlap
    EXCLUDE USING gist (
      event_id WITH =,
      candidate_id WITH =,
      tstzrange(start_time, end_time, '[)') WITH &&
    )
);

CREATE INDEX event_candidate_availability_event_candidate_idx
  ON event_candidate_availability (event_id, candidate_id, start_time);

COMMIT;
